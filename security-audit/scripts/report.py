#!/usr/bin/env python3
"""Render audit JSON results into a markdown report skeleton.

Usage:
  python3 report.py --results results --out results/REPORT.md \
      --version 1.7.12 --code 21 --apk app-release.apk
"""
from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter
from pathlib import Path


def load(path: Path):
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="results/REPORT.md")
    ap.add_argument("--version", default="?")
    ap.add_argument("--code", default="?")
    ap.add_argument("--apk", default="")
    args = ap.parse_args()
    res = Path(args.results)
    static = load(res / "static.json")
    crypto = load(res / "crypto.json")
    secrets = load(res / "secrets.json")
    device = load(res / "device.json")

    apk_line = ""
    if args.apk and Path(args.apk).exists():
        p = Path(args.apk)
        apk_line = f"**APK:** `{p.name}` · {p.stat().st_size} B · `sha256 {sha256(p)}`"

    findings = []
    if static:
        for lead in static.get("leads", []):
            findings.append({
                "id": f"VZ-{lead['area'].upper()}-auto",
                "severity": lead["severity"], "title": lead["message"], "area": lead["area"],
            })
    if crypto:
        for f in crypto.get("findings", []):
            if f["severity"] in ("critical", "high", "medium"):
                findings.append({"id": "VZ-CRYPTO-auto", "severity": f["severity"],
                                 "title": f["title"], "area": f["area"]})
    if secrets:
        for h in secrets.get("hits", []):
            if h["severity"] in ("critical", "high"):
                findings.append({"id": "VZ-SECRETS-auto", "severity": h["severity"],
                                 "title": f"{h['rule']} in {h['origin']}:{h['line']}", "area": "secrets"})

    counts = Counter(f["severity"] for f in findings)
    rows = "\n".join(
        f"| {f['id']} | {f['severity'].capitalize()} | {f['title']} | {f['area']} | Open |"
        for f in findings
    ) or "| — | — | No automated findings | — | — |"

    md = f"""# VaultZero — Security Audit (automated pass)

**Version:** {args.version} ({args.code}) · **Date:** {__import__('datetime').date.today()}
{apk_line}

> This file is generated by `security-audit/scripts/report.py`. Manual findings from
> `references/report-template.md` must be merged before sign-off.

## Automated findings

| ID | Severity | Title | Area | Status |
| --- | --- | --- | --- | --- |
{rows}

## Counts

| Severity | Count |
| --- | ---: |
| Critical | {counts.get('critical', 0)} |
| High | {counts.get('high', 0)} |
| Medium | {counts.get('medium', 0)} |
| Low | {counts.get('low', 0)} |

## Raw evidence

- `static.json` — manifest, components, build flags, risky API leads
- `crypto.json` — KDF constants, AEAD/Keystore checks
- `secrets.json` — repository/APK secret scan
- `device/` — on-device evidence

## Manual sections to complete

1. Scope, devices, API levels, dates.
2. Crypto review verdicts (bit-flip, KDF downgrade, biometric re-enrolment).
3. Storage/backup findings (run-as inspection, fuzz corpus results).
4. Platform/UI findings (screenshots, clipboard, intents, tapjacking).
5. MASVS checklist (`references/masvs-checklist.csv`) with Pass/Fail/N/A.
6. Residual risk and sign-off.
"""
    Path(args.out).write_text(md)
    print(f"wrote {args.out} ({len(findings)} automated findings)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
